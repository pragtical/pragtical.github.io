#!/usr/bin/env python3
"""Export Pragtical renderer operations as a self-contained, recolorable SVG.

Requires fontTools. Fonts are outlined, not substituted by browser fonts.
"""

import argparse
import json
from pathlib import Path
import xml.etree.ElementTree as ET

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont


def number(value):
    return f"{value:.5f}".rstrip("0").rstrip(".") if value else "0"


def bounds(operation):
    # Match renderer.c's rect_to_grid, including fractional coordinates.
    x, y = int(operation["x"] + 0.5), int(operation["y"] + 0.5)
    return {"x": x, "y": y, "width": max(0, int(operation["x"] + operation["w"] + 0.5) - x), "height": max(0, int(operation["y"] + operation["h"] + 0.5) - y)}


def export(draw_list, destination):
    ET.register_namespace("", "http://www.w3.org/2000/svg")
    namespace = "{http://www.w3.org/2000/svg}"

    def element(parent, tag, **attrs):
        return ET.SubElement(parent, namespace + tag, {key.replace("_", "-"): str(value) for key, value in attrs.items()})

    root = ET.Element(namespace + "svg", {"viewBox": f"0 0 {draw_list['width']} {draw_list['height']}"})
    element(root, "title").text = "Pragtical with SCM and Lua language-server completions"
    element(root, "desc").text = "Exported from the actual editor renderer at 1920 by 1080, with One Dark and 200% UI scale."
    element(root, "metadata").text = "Generated by scripts/colors-preview from Pragtical's renderer. Glyph outlines: Fira Sans, JetBrains Mono, Pragtical icons, and LSP symbols."
    definitions = element(root, "defs")
    fonts, outlines, clips = {}, {}, {}
    group = root

    def font(path):
        if path not in fonts:
            fonts[path] = TTFont(path)
        return fonts[path]

    def paint(color):
        r, g, b, a = color["rgba"]
        fallback = f"#{int(r):02x}{int(g):02x}{int(b):02x}" if a == 255 else f"rgba({r},{g},{b},{number(a / 255)})"
        return f"var(--editor-{color['role'].replace('.', '-')}, {fallback})" if color.get("role") else fallback

    for operation in draw_list["operations"]:
        kind = operation["kind"]
        if kind == "clip":
            clip_bounds = tuple(operation[key] for key in ("x", "y", "w", "h"))
            if clip_bounds not in clips:
                identity = f"clip{len(clips)}"
                clips[clip_bounds] = identity
                clip = element(definitions, "clipPath", id=identity)
                element(clip, "rect", **bounds(operation))
            group = element(root, "g", clip_path=f"url(#{clips[clip_bounds]})")
        elif kind == "rect":
            if operation["w"] > 0 and operation["h"] > 0:
                element(group, "rect", **bounds(operation), fill=paint(operation["color"]))
        elif kind == "poly":
            commands = []
            for point in operation["points"]:
                commands.append(("M" if not commands else "L") + " ".join(map(number, point[:2])))
                if len(point) == 6:
                    commands.append("Q" + " ".join(map(number, point[2:])))
                elif len(point) == 8:
                    commands.append("C" + " ".join(map(number, point[2:])))
            element(group, "path", d=" ".join(commands) + "Z", fill=paint(operation["color"]))
        elif kind == "text":
            paths = operation["font"] if isinstance(operation["font"], list) else [operation["font"]]
            base = font(paths[0])
            baseline = int(base["hhea"].ascent * operation["size"] / base["head"].unitsPerEm)
            text_group = element(group, "g", fill=paint(operation["color"]), aria_label=operation["text"])
            for codepoint, offset in operation["glyphs"]:
                if chr(codepoint).isspace():
                    continue
                path = next((path for path in paths if codepoint in font(path).getBestCmap()), None)
                if not path:
                    raise ValueError(f"Missing glyph: U+{codepoint:04X}")
                face = font(path)
                glyph_name = face.getBestCmap()[codepoint]
                identity = (path, glyph_name)
                if identity not in outlines:
                    glyph_set = face.getGlyphSet()
                    pen = SVGPathPen(glyph_set)
                    glyph_set[glyph_name].draw(pen)
                    outlines[identity] = f"glyph{len(outlines)}"
                    element(definitions, "path", id=outlines[identity], d=pen.getCommands())
                scale = operation["size"] / face["head"].unitsPerEm
                x, y = operation["x"] + offset, operation["y"] + baseline
                element(text_group, "use", href=f"#{outlines[identity]}", transform=f"translate({number(x)} {number(y)}) scale({number(scale)} {number(-scale)})")
        else:
            raise ValueError(f"Unsupported renderer operation: {kind}")
    ET.indent(root, space="  ")
    Path(destination).parent.mkdir(parents=True, exist_ok=True)
    ET.ElementTree(root).write(destination, encoding="unicode")
    print(f"Exported {len(draw_list['operations'])} operations, {len(outlines)} glyph outlines to {destination}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("draw_list", type=Path)
    parser.add_argument("output", type=Path)
    arguments = parser.parse_args()
    export(json.loads(arguments.draw_list.read_text()), arguments.output)
